#!/usr/bin/env python3
"""Convert a Manim batch manifest (out/batch1_manifest.json) into the Mini App
content.js manifest (contract enforced by validateContent() in app.js).

Field mapping:
  topics[].id            -> topicId
  topics[].file          -> videoUrl: assets/<file>
  (derived)              -> poster:   assets/posterNN.jpg  (NN = last 2 chars of id)
  topics[].duration      -> duration (rounded, seconds)
  checkpoints[].timestamp    -> t
  checkpoints[].correct_index-> correctIndex
  checkpoints[].id           -> id (extra field, allowed)
  question/options/hint      -> same

Usage:
  python3 build_content.py --manifest ~/src/manim-vertical/out/batch1_manifest.json \
                           --out ~/src/interactive-lessons/mathkids
"""
import argparse
import json
import os


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--manifest', required=True, help='path to batch manifest JSON')
    ap.add_argument('--out', required=True, help='target app dir (contains index.html)')
    ap.add_argument('--assets-subdir', default='assets')
    args = ap.parse_args()

    with open(args.manifest, encoding='utf-8') as f:
        m = json.load(f)

    topics = []
    for t in m['topics']:
        cps = []
        for cp in t['checkpoints']:
            cps.append({
                't': cp['timestamp'],
                'question': cp['question'],
                'options': cp['options'],
                'correctIndex': cp['correct_index'],
                'hint': cp['hint'],
            })
            if cp.get('id'):
                cps[-1]['id'] = cp['id']
        topics.append({
            'topicId': t['id'],
            'title': t['title'],
            'grade': t.get('grade'),
            'videoUrl': f"{args.assets_subdir}/{t['file']}",
            'poster': f"{args.assets_subdir}/poster{t['id'][-2:]}.jpg",
            'duration': round(t['duration'], 2),
            'checkpoints': cps,
        })

    header = (
        "/* GENERATED by build_content.py from %s — do not edit by hand,\n"
        "   rerun the script. Contract: README.md / validateContent() in app.js. */\n"
        % os.path.basename(args.manifest)
    )
    body = json.dumps(topics, ensure_ascii=False, indent=2)
    out_path = os.path.join(args.out, 'content.js')
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(header + 'window.CONTENT = ' + body + ';\n')

    n_cp = sum(len(t['checkpoints']) for t in topics)
    print(f"wrote {out_path}: {len(topics)} topics, {n_cp} checkpoints")


if __name__ == '__main__':
    main()
